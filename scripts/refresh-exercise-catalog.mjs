// Rebuilds src/tools/exercise-catalog.ts from Garmin's exercise catalog.
//
//   1. Download https://connect.garmin.com/web-data/exercises/Exercises.json
//      (open it in a browser and save the page).
//   2. node scripts/refresh-exercise-catalog.mjs path/to/Exercises.json
//
// Only the category and exercise codes are kept; muscles are not used.
import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/refresh-exercise-catalog.mjs path/to/Exercises.json');
  process.exit(1);
}

const { categories } = JSON.parse(readFileSync(source, 'utf8'));
if (!categories || typeof categories !== 'object') {
  console.error('No "categories" object found. Is this Garmin\'s Exercises.json?');
  process.exit(1);
}

const lines = Object.entries(categories).map(([category, { exercises = {} }]) => {
  const names = `'${Object.keys(exercises).join(' ')}'`;
  const oneLine = `  ${category}: ${names},`;
  return oneLine.length <= 100 ? oneLine : `  ${category}:\n    ${names},`;
});
// No trailing comma on the last entry, matching the rest of the codebase.
lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');

const out = `// Generated by scripts/refresh-exercise-catalog.mjs from Garmin's catalog at
// https://connect.garmin.com/web-data/exercises/Exercises.json — names only.
// Re-run that script against a fresh download rather than editing by hand.

const RAW: Record<string, string> = {
${lines.join('\n')}
};

/** Category code → the exercise codes Garmin accepts under it. */
export const EXERCISE_CATALOG: ReadonlyMap<string, ReadonlySet<string>> = new Map(
  Object.entries(RAW).map(([category, names]) => [category, new Set(names.split(' '))])
);
`;

const target = new URL('../src/tools/exercise-catalog.ts', import.meta.url);
writeFileSync(target, out);
const total = Object.values(categories).reduce(
  (n, c) => n + Object.keys(c.exercises ?? {}).length,
  0
);
console.log(`Wrote ${Object.keys(categories).length} categories, ${total} exercises.`);
